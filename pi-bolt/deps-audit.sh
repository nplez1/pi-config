#!/bin/sh
# Keep the two npm trees on this machine free of known-vulnerable dependencies.
#
#   deps-audit.sh            fix what is fixable, quietly; say only what changed
#   deps-audit.sh --check    report and exit 1 if either tree is not clean; change nothing
#   deps-audit.sh --verbose  print each tree's verdict whether or not it changed
#
# The two trees, and why they are ours to keep clean:
#
#   ~/.pi/agent/npm                      every package in it is an extension
#   ~/.pi/agent/install/releases/<ver>   the managed pi that `pi-real` runs
#
# Nothing upstream will do it for us: both pin `undici` to 8.10.2 exactly through
# `@earendil-works/pi-coding-agent` (Pi itself, and a dependency of most
# extensions), and that version carries three advisories. `npm audit fix` cannot
# move an exact pin — it offers only `--force`, whose suggestion is to downgrade
# `@tintinweb/pi-subagents`, a breaking change that fixes nothing. So an
# `overrides` entry does it (a patch bump inside 8.x), and `npm audit fix` handles
# everything the packages' own ranges allow.
#
# The managed release's package.json is regenerated by every `pi update`, so this
# has to be re-applied, not applied once. Two callers do that: `install.sh`, and
# the `pi` shim (pi-swap.sh) after any `pi update`, which is the one command that
# moves what is installed. Running `pi-bolt update` or `pi-real update` directly
# skips the shim; re-run this script, or `install.sh`, to catch up.
#
# Exit status is 0 unless `--check` found something, so a caller can run it after
# a command without changing that command's exit code.
set -u

UNDICI=${PI_UNDICI_OVERRIDE:-^8.12.3}
AGENT=${PI_AGENT_DIR:-$HOME/.pi/agent}
quiet=1
check_only=0

while [ $# -gt 0 ]; do
  case "$1" in
    --check) check_only=1 ;;
    --verbose | -v) quiet=0 ;;
    --help | -h)
      awk 'NR==1{next} /^#/{sub(/^# ?/,""); print; next} {exit}' "$0"
      exit 0
      ;;
    *)
      echo "deps-audit.sh: unknown argument: $1" >&2
      exit 2
      ;;
  esac
  shift
done

command -v npm >/dev/null 2>&1 || {
  echo "deps-audit.sh: npm is not on PATH; nothing checked" >&2
  exit 0   # never fail a shell over this
}

trouble=0

summary_of() {
  # npm's own tally line, wherever it sits; the last line otherwise (an error).
  printf '%s\n' "$1" | grep -m1 -E '^[0-9]+ vulnerabilit(y|ies)' \
    || printf '%s\n' "$1" | tail -1
}
clean_word() { case "$1" in *"0 vulnerabilities"*) return 0 ;; esac; return 1; }
# An audit that errored is not an audit that found nothing: say the difference.
vuln_word() { case "$1" in *vulnerabilit*) return 0 ;; esac; return 1; }

audit_tree() {
  dir=$1
  [ -f "$dir/package.json" ] || return 0
  label=${dir#"$HOME"/}
  changed=""

  # 1. The pin. `npm pkg get` prints the value quoted, or {} where the key is absent.
  have=$(cd "$dir" && npm pkg get overrides.undici 2>/dev/null | tr -d '"' || true)
  case "$have" in "" | "{}" | "undefined") have="" ;; esac
  if [ "$have" != "$UNDICI" ]; then
    if [ "$check_only" = 1 ]; then
      echo "deps-audit: $label: undici override is ${have:-missing}, want $UNDICI" >&2
      trouble=1
    elif (cd "$dir" && npm pkg set "overrides.undici=$UNDICI" >/dev/null 2>&1); then
      changed="pinned undici $UNDICI"
    else
      echo "deps-audit: $label: could not set the undici override" >&2
      trouble=1
    fi
  fi

  # 2. Install, but only when the pin actually changed: a needless reinstall here
  #    also prunes extraneous packages, which is not what a visitor of `pi update`
  #    should be paying for. --omit=dev matches what the pi installer runs.
  if [ -n "$changed" ]; then
    (cd "$dir" && npm install --omit=dev --legacy-peer-deps --no-audit --no-fund >/dev/null 2>&1) \
      || echo "deps-audit: $label: npm install failed after pinning undici" >&2
  fi

  # 3. Audit. Anything left after `npm audit fix` needs a human: an exact pin that
  #    `--force` would move by downgrading something else, or an advisory with no
  #    fixed version at all.
  before=$(cd "$dir" && npm audit 2>&1 || true)
  was=$(summary_of "$before")
  if clean_word "$was"; then
    : # nothing to do
  elif ! vuln_word "$was"; then
    printf 'deps-audit: %s: npm audit did not run (%s)\n' "$label" "$was" >&2
  elif [ "$check_only" = 1 ]; then
    printf 'deps-audit: %s: %s\n' "$label" "$was" >&2
    trouble=1
  elif (cd "$dir" && npm audit fix >/dev/null 2>&1); then
    after=$(cd "$dir" && npm audit 2>&1 || true)
    if clean_word "$(summary_of "$after")"; then
      changed="${changed:+$changed; }npm audit fix cleared it (was: $was)"
    else
      printf 'deps-audit: %s: %s after `npm audit fix` — see pi-bolt/README.md, Dependencies\n' \
        "$label" "$(summary_of "$after")" >&2
      trouble=1
    fi
  else
    printf 'deps-audit: %s: `npm audit fix` failed (was: %s)\n' "$label" "$was" >&2
    trouble=1
  fi

  if [ -n "$changed" ]; then
    printf 'pi deps: %s: %s\n' "$label" "$changed"
  elif [ "$quiet" = 0 ]; then
    printf 'pi deps: %s: clean\n' "$label"
  fi
}

audit_tree "$AGENT/npm"
pi_version=$(cat "$AGENT/install/current-version" 2>/dev/null || true)
if [ -n "$pi_version" ]; then
  audit_tree "$AGENT/install/releases/$pi_version"
fi

[ "$check_only" = 1 ] && [ "$trouble" = 0 ] && [ "$quiet" = 0 ] && echo "pi deps: clean"

exit "$trouble"

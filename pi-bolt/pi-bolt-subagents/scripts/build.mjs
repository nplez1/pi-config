/**
 * Build the pi-config subagents fork into the "dist-bun" shape Pi-Bolt loads natively.
 *
 * Pi evaluates an extension's entry through jiti, which transpiles TypeScript at
 * every start. The fix (the one OpenSec's own bundles use) is to keep the entry
 * tiny and hand the real work to a single CommonJS file that Bun `require`s
 * natively, so it is never transpiled:
 *
 *   dist-bun/index.js   the jiti shim: imports Pi's modules, publishes them on a
 *                       global, then require()s core.cjs
 *   dist-bun/core.cjs   the whole extension, bundled, host modules left out
 *
 * `core.cjs` cannot `require("@earendil-works/pi-coding-agent")` directly: it is
 * loaded outside jiti's module graph, where Pi's aliases do not resolve. So the
 * host imports are rewritten to a lookup on the global the shim sets.
 *
 * Run:  bun scripts/build.mjs [--watch-source DIR]
 * (Reads the fork's source; never writes to it.)
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { freshnessSnippet, writeBuildInfo } from "../../lib/bundle-info.mjs";

const HERE = dirname(dirname(fileURLToPath(import.meta.url)));

/** Where the sourcetree lives. Read-only input. */
const SOURCE =
  process.env.SUBAGENTS_SOURCE ??
  resolve(HERE, "../../plugins/pi-subagents");
const OUT = join(HERE, "dist-bun");

const pkg = JSON.parse(readFileSync(join(SOURCE, "package.json"), "utf8"));
const NAME = "@nplez1/pi-bolt-subagents";
const VERSION = `${pkg.version}-pibolt.1`;
const KEY = `${NAME}@${pkg.version}:host-modules`;

/** What this bundle is a snapshot of — recorded in build-info.json, checked on every load. */
const VERSION_FILE = join(SOURCE, "package.json");
const INPUTS = [join(SOURCE, "src"), VERSION_FILE];
const REBUILD_COMMAND = join(dirname(HERE), "rebuild.sh");

/**
 * The modules Pi provides to the extension. Everything listed here is left out
 * of the bundle and looked up on the global; everything else (croner, nanoid,
 * node: builtins) is bundled or kept external by Bun.
 *
 * "@sinclair/typebox" is aliased to the bare `typebox` module: Pi exposes the
 * latter, and OpenSec's bundles do the same.
 */
const HOSTS = new Map([
  ["@earendil-works/pi-coding-agent", "@earendil-works/pi-coding-agent"],
  ["@earendil-works/pi-ai", "@earendil-works/pi-ai"],
  ["@earendil-works/pi-tui", "@earendil-works/pi-tui"],
  ["typebox", "typebox"],
  ["@sinclair/typebox", "typebox"],
  ["typebox/value", "typebox/value"],
]);

const hostPlugin = {
  name: "pi-host-modules",
  setup(build) {
    build.onResolve({ filter: /.*/ }, (args) => {
      // Only a bare specifier we know, never a relative path or a subpath.
      if (!HOSTS.has(args.path)) return undefined;
      return { path: `pi-host:${args.path}`, namespace: "pi-host" };
    });
    build.onLoad({ filter: /.*/, namespace: "pi-host" }, (args) => {
      const spec = args.path.slice("pi-host:".length);
      return {
        contents: `module.exports = globalThis[Symbol.for(${JSON.stringify(KEY)})](${JSON.stringify(spec)});\n`,
        loader: "js",
      };
    });
  },
};

const result = await Bun.build({
  entrypoints: [join(SOURCE, "src/index.ts")],
  target: "bun",
  format: "cjs",
  plugins: [hostPlugin],
  // A bundle we can diff against the source when something misbehaves.
  minify: false,
  sourcemap: "none",
  define: { "process.env.PI_BOLT_BUNDLE": JSON.stringify(VERSION) },
});

if (!result.success) {
  for (const log of result.logs) console.error(log);
  process.exit(1);
}

mkdirSync(OUT, { recursive: true });

const outputs = result.outputs.filter((o) => o.kind === "entry-point");
if (outputs.length !== 1) {
  console.error(`expected 1 entry point output, got ${outputs.length}`);
  process.exit(1);
}
writeFileSync(join(OUT, "core.cjs"), await outputs[0].text());

/** The shim, in the shape Pi-Bolt's own bundles use. */
const shim = `// Generated by scripts/build.mjs — the Pi entry point of the Bun build of ${pkg.name} ${pkg.version}.
//
// Pi evaluates this file through jiti (which transforms it); the extension
// itself is core.cjs, loaded with Bun's native require so it is never
// transformed. The host-provided modules core.cjs needs are only reachable
// through jiti, so they are imported here and handed over on a global.
import { createRequire } from "node:module";
import { readFileSync, readdirSync, statSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
${freshnessSnippet()}
import * as hostCodingAgent from "@earendil-works/pi-coding-agent";
import * as hostAi from "@earendil-works/pi-ai";
import * as hostTui from "@earendil-works/pi-tui";
import * as hostTypebox from "typebox";
import * as hostTypeboxValue from "typebox/value";

const hostModules = {
  "@earendil-works/pi-coding-agent": hostCodingAgent,
  "@earendil-works/pi-ai": hostAi,
  "@earendil-works/pi-tui": hostTui,
  "typebox": hostTypebox,
  "@sinclair/typebox": hostTypebox,
  "typebox/value": hostTypeboxValue,
};
globalThis[Symbol.for(${JSON.stringify(KEY)})] = (id) => {
  const mod = hostModules[id];
  if (mod === undefined) throw new Error(${JSON.stringify(
    `${NAME}: host module `,
  )} + id + " is not available");
  return mod;
};

const nativeRequire = createRequire(import.meta.url);
const corePath = nativeRequire.resolve("./core.cjs");
// A fresh evaluation per load, as jiti gives every other extension (/reload).
delete nativeRequire.cache[corePath];
const core = nativeRequire(corePath);

export default core.default;
`;
writeFileSync(join(OUT, "index.js"), shim);

const info = writeBuildInfo({
  bundleDir: HERE,
  name: NAME,
  version: VERSION,
  sourceDescription: `${pkg.name}@${pkg.version} (${SOURCE})`,
  inputs: INPUTS,
  sourceVersion: pkg.version,
  versionFile: VERSION_FILE,
  rebuildCommand: REBUILD_COMMAND,
});

const coreKb = (readFileSync(join(OUT, "core.cjs")).length / 1024).toFixed(0);
console.log(`built ${NAME} from ${pkg.name}@${pkg.version}`);
console.log(`  recorded ${JSON.stringify(info.fingerprint)} in build-info.json`);
console.log(`  source : ${SOURCE}`);
console.log(`  core.cjs ${coreKb} KB`);
console.log(`  index.js shim, host key "${KEY}"`);
